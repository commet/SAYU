export function buildSystemPrompt(
  aptType: string,
  artworkTitle: string,
  artworkArtist: string,
  stage: SessionStage
): string {
  const normalizedType = aptType.toUpperCase();
  const personality = APT_PERSONALITIES[normalizedType] ?? APT_PERSONALITIES['LAEF'];

  const parts = [
    BASE_PROMPT(artworkTitle, artworkArtist),
    personality,
    STAGE_INSTRUCTIONS[stage],
  ];

  return parts.filter(Boolean).join('\n\n');
}
